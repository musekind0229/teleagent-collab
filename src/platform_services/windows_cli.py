"""Conservative cmd/bat LaunchSpec construction (no launch or temp files).

The ``@`` command prefix is deliberate: it keeps /s /c from stripping the
first and last quotes generated by Python's Windows list2cmdline. Keep each
operand separate; embedding quoted command text in an argv item would cause
list2cmdline to emit backslash-quotes, which cmd does NOT decode like the CRT.
Only the validated support set below is safe for this encoding. This does
not make an untrusted batch file safe, nor control how that file uses %*.
"""
from __future__ import annotations

import ntpath
import os
from typing import Mapping

from .cli import CliLaunchError, LaunchSpec, WRAPPER_WINDOWS_CMD

_FORBIDDEN = frozenset('\x00\r\n"^&|<>%!()')


def _check(value: str, what: str) -> None:
    if not isinstance(value, str):
        raise CliLaunchError(f"{what} must be str")
    if any(ch in _FORBIDDEN for ch in value):
        raise CliLaunchError(f"{what} contains unsupported cmd characters")


class CmdWrapper:
    """Build an explicit system-cmd launch; injected cmd_exe is for tests.

    Resolution happens at wrap time so an explicit env never borrows the
    parent's SystemRoot/WINDIR. The test override need not exist on disk.
    """

    def __init__(self, *, cmd_exe: str | None = None):
        if cmd_exe is not None:
            _check(cmd_exe, "cmd_exe")
            if not cmd_exe or not os.path.isabs(cmd_exe):
                raise CliLaunchError("cmd_exe must be an absolute test path")
        self._cmd_exe = cmd_exe

    def _resolve_cmd(self, env: Mapping[str, str] | None) -> str:
        if self._cmd_exe is not None:
            return self._cmd_exe
        source = os.environ if env is None else env
        # Windows environment variable names are case-insensitive, including
        # plain mappings supplied by callers. Never consult PATH or COMSPEC.
        roots = {k.upper(): v for k, v in source.items()
                 if isinstance(k, str) and k.upper() in ("SYSTEMROOT", "WINDIR")}
        for key in ("SYSTEMROOT", "WINDIR"):
            root = roots.get(key)
            if root is None:
                continue
            _check(root, key)
            drive, tail = ntpath.splitdrive(root)
            if not drive or not tail.startswith(("\\", "/")) or drive.startswith("\\"):
                raise CliLaunchError(f"{key} must be a local absolute system directory")
            candidate = ntpath.join(root, "System32", "cmd.exe")
            if os.path.isfile(candidate):
                return candidate
        raise CliLaunchError("cannot locate System32\\cmd.exe from supplied SystemRoot/WINDIR")

    def wrap(
        self,
        script: str,
        args: tuple[str, ...],
        cwd: str | None,
        env: Mapping[str, str] | None,
    ) -> LaunchSpec:
        _check(script, "script")
        if not script or ntpath.splitext(script)[1].lower() not in (".cmd", ".bat"):
            raise CliLaunchError("script must name a .cmd or .bat file")
        if not isinstance(args, tuple):
            raise CliLaunchError("args must be a tuple of str, not a command string")
        for arg in args:
            _check(arg, "arg")
            if arg.endswith("\\"):
                raise CliLaunchError("args ending in backslash are unsupported")
        # A bare filename must not search PATH or resolve as a cmd builtin.
        if not ntpath.dirname(script):
            script = ".\\" + script
        cmd = self._resolve_cmd(env)
        return LaunchSpec((cmd, "/d", "/v:off", "/s", "/c", "@", script, *args),
                          cwd, env, WRAPPER_WINDOWS_CMD)
